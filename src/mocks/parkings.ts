/** Every day of the week with the same window. */
const daily = (opensAt: number, closesAt: number): OpeningHours[] =>
  [0, 1, 2, 3, 4, 5, 6].map((weekday) => ({ weekday, opensAt, closesAt }));

/** Weekdays and weekend with different windows. */
const split = (
  week: [number, number],
  weekend: [number, number],
): OpeningHours[] =>
  [0, 1, 2, 3, 4, 5, 6].map((weekday) => {
    const isWeekend = weekday === 0 || weekday === 6;
    const [opensAt, closesAt] = isWeekend ? weekend : week;
    return { weekday, opensAt, closesAt };
  });

